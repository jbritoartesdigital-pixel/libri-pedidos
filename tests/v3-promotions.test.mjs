import test from 'node:test';
import assert from 'node:assert/strict';
import {database} from './helpers.mjs';
import {quoteV3Cart} from '../src/lib/v3-cart-quote.js';
import {setAtelieSaleStatus} from '../src/lib/v3-atelie-release.js';
import {activeV3CombinedCampaign,createV3CombinedCampaign,pauseV3CombinedCampaign} from '../src/lib/v3-promotions.js';
const invite={productCode:'interactive_essential',variantCode:'interactive_essential_default',addonCodes:[]};
const atelie={productCode:'atelie_essencia',variantCode:'atelie_essencia_default',addonCodes:[],extras:[{code:'atelie_pose',quantity:1}]};
const cart={eventType:'birthday',paymentMethod:'pix',items:[invite,atelie]};
test('best monetary discount wins; eligible coupon cannot discount unrelated services or new extras',async()=>{
 const db=database();await setAtelieSaleStatus(db,'essencia',true);
 db.sqlite.prepare("INSERT INTO v2_coupons(code,discount_type,discount_value,restrictions_json) VALUES('ATELIE10','percent',10,?)").run(JSON.stringify({productCodes:['atelie_essencia'],eventTypes:['birthday']}));
 db.sqlite.exec("INSERT INTO v2_coupons(code,discount_type,discount_value) VALUES('SMALL','fixed',500)");
 let q=await quoteV3Cart(db,{...cart,couponCode:'atelie10'},{includeSnapshots:true});
 assert.equal(q.selectedDiscount,'coupon');assert.equal(q.couponDiscountCents,1590);assert.equal(q.combinedDiscountCents,0);
 assert.equal(q.totalCents,19810);assert.equal(q.pointsUnits,450);
 assert.deepEqual(q.items.map(x=>x.discountCents),[0,1590]);
 assert.equal(q.items[1].commercialSnapshot.coupon.code,'ATELIE10');
 q=await quoteV3Cart(db,{...cart,couponCode:'small'});
 assert.equal(q.selectedDiscount,'combined');assert.equal(q.discountCents,970);assert.equal(q.couponComparison.applied,false);
 assert.equal(q.totalCents,20430);
 await assert.rejects(quoteV3Cart(db,{...cart,eventType:'wedding',couponCode:'ATELIE10'}),/condições/);
 db.sqlite.exec("UPDATE v2_coupons SET max_uses=1 WHERE code='SMALL'");
 await assert.rejects(quoteV3Cart(db,{...cart,couponCode:'SMALL'}),/limite de usos/);
 assert.equal(db.sqlite.prepare('SELECT COUNT(*) AS n FROM v2_coupon_uses').get().n,0);
});
test('temporary combined campaigns reject overlap, expire automatically, and can be paused',async()=>{
 const db=database();await setAtelieSaleStatus(db,'essencia',true);
 const now=Date.now(),start=new Date(now-3600000).toISOString(),end=new Date(now+3600000).toISOString();
 const rows=await createV3CombinedCampaign(db,{name:'Semana especial',twoPercent:8,threePercent:12,startsAt:start,endsAt:end});
 assert.equal(rows.length,1);
 await assert.rejects(createV3CombinedCampaign(db,{name:'Sobreposta',twoPercent:8,threePercent:12,startsAt:start,endsAt:end}),/sobreposto/);
 const q=await quoteV3Cart(db,cart);
 assert.equal(q.combinedDiscountPercent,8);assert.equal(q.discountCents,1552);assert.equal(q.campaign.name,'Semana especial');
 assert.equal(await activeV3CombinedCampaign(db,new Date(now+7200000)),null);
 await pauseV3CombinedCampaign(db,rows[0].id);
 const fallback=await quoteV3Cart(db,cart);
 assert.equal(fallback.combinedDiscountPercent,5);assert.equal(fallback.discountCents,970);
});
